import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { beforeAll, describe, expect, it } from 'vitest'
import { generateTypes, runGenTypes } from '../../src/cli/gen-types.js'
import { TEST_SCHEMA, TEST_URL, canConnect, resetFixture } from '../helpers/db.js'

const available = await canConnect()
const S = TEST_SCHEMA

describe.skipIf(!available)('gen-types', () => {
  let src: string

  beforeAll(async () => {
    await resetFixture()
    src = await generateTypes({ connection: TEST_URL, schemas: [S], comments: false })
  })

  it('emits the Json helper and Database type', () => {
    expect(src).toContain('export type Json =')
    expect(src).toContain('export type Database = {')
    expect(src).toContain(`> = Database['${S}']['Tables'][T]['Row']`)
  })

  it('renders enums', () => {
    expect(src).toContain('pf_mood: "low" | "medium" | "high"')
  })

  it('renders views with resolvable columns', () => {
    const viewStart = src.indexOf('    Views: {')
    expect(viewStart).toBeGreaterThan(-1)
    const view = src.slice(viewStart)
    expect(view).toContain('      pf_event_summary: {')
    expect(view).toContain(`mood: Database["${S}"]["Enums"]["pf_mood"] | null`)
  })

  it('resolves domains, arrays and composites in columns', () => {
    expect(src).toContain('contact: string | null')
    expect(src).toContain('scores: (number)[] | null')
    expect(src).toContain(`pos: Database["${S}"]["CompositeTypes"]["pf_point"] | null`)
  })

  it('renders user-defined composite types only', () => {
    const start = src.indexOf('    CompositeTypes: {')
    const body = src.slice(start)
    expect(body).toContain('      pf_point: {')
    expect(body).toContain('        x: number | null')
    expect(body).not.toContain('      pf_events: {')
    expect(body).not.toContain('      pf_todos: {')
  })

  it('marks identity/default columns optional and omits generated columns from writes', () => {
    const tableStart = src.indexOf('      pf_events: {')
    const insertStart = src.indexOf('        Insert: {', tableStart)
    const insertEnd = src.indexOf('        }', insertStart)
    const row = src.slice(tableStart, insertStart)
    const insert = src.slice(insertStart, insertEnd)
    expect(row).toContain('note_len: number | null')
    expect(insert).not.toContain('note_len')
    expect(insert).toContain('id?: number')
    expect(insert).toContain('note?: string | null')
    expect(insert).toContain(`mood: Database["${S}"]["Enums"]["pf_mood"]`)
  })

  it('renders foreign key relationships with cardinality', () => {
    const tableStart = src.indexOf('      pf_audit: {')
    const block = src.slice(tableStart)
    expect(block).toContain('foreignKeyName: "pf_audit_event_id_fkey"')
    expect(block).toContain('isOneToOne: true')
    expect(block).toContain('referencedRelation: "pf_events"')
  })

  it('renders functions with args and resolvable return types', () => {
    expect(src).toContain('pf_events_of: {')
    expect(src).toContain(`Args: { m: Database["${S}"]["Enums"]["pf_mood"] }`)
    expect(src).toContain(`Returns: (Database["${S}"]["Tables"]["pf_events"]["Row"])[]`)
    expect(src).toContain('Args: Record<PropertyKey, never>')
    expect(src).toContain('Returns: (number)[]')
  })

  it('adds a header by default and omits it when comments are disabled', async () => {
    const withComments = await generateTypes({ connection: TEST_URL, schemas: [S] })
    expect(withComments).toContain('// Auto-generated by pg-fluent gen-types.')
    expect(src).not.toContain('// Auto-generated by pg-fluent gen-types.')
  })

  it('writes to --out and errors without a connection string', async () => {
    const dir = await mkdtemp(join(tmpdir(), 'pgfluent-gen-'))
    const out = join(dir, 'types.ts')
    try {
      const previous = process.env['DATABASE_URL']
      delete process.env['DATABASE_URL']
      await expect(runGenTypes([])).rejects.toThrow(/connection string is required/i)
      if (previous !== undefined) process.env['DATABASE_URL'] = previous
      await runGenTypes(['--connection', TEST_URL, '--schema', S, '--no-comments', '--out', out])
      const written = await readFile(out, 'utf8')
      expect(written).toContain('export type Database = {')
    } finally {
      await rm(dir, { recursive: true, force: true })
    }
  })
})
